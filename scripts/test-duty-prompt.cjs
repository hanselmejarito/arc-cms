const fs=require('fs'),ts=require('typescript'),assert=require('node:assert/strict')
const js=ts.transpileModule(fs.readFileSync('src/dutyPrompt.js','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText
const out={};new Function('exports',js)(out)
const branches=[{status:'Active',night:true}]
const options=(record,extra={})=>out.dutyPromptOptions({record,branches,enabled:true,...extra})
assert.deepEqual(options(null),{morning:true,night:true})
assert.deepEqual(options({in:'08:00',out:''}),{morning:false,night:false})
assert.deepEqual(options({in:'08:00',out:'17:00'}),{morning:false,night:true})
assert.deepEqual(options({in:'08:00',out:'17:00',nightIn:'17:30'}),{morning:false,night:false})
assert.deepEqual(options(null,{branches:[{status:'Inactive',night:true}]}),{morning:true,night:false})
assert.deepEqual(options(null,{blocked:true}),{morning:false,night:false})
assert.deepEqual(options(null,{enabled:false}),{morning:true,night:false})
const values=new Map()
const storage={getItem:key=>values.get(key),setItem:(key,value)=>values.set(key,value)}
const morning=out.dutyPromptDismissalKey('user-1','2026-11-17',options(null))
const night=out.dutyPromptDismissalKey('user-1','2026-11-17',options({in:'08:00',out:'17:00'}))
out.dismissDutyPrompt(storage,morning)
assert.equal(out.wasDutyPromptDismissed(storage,morning),true)
assert.equal(out.wasDutyPromptDismissed(storage,night),false)
assert.equal(out.wasDutyPromptDismissed(storage,out.dutyPromptDismissalKey('user-2','2026-11-17',options(null))),false)
assert.equal(out.wasDutyPromptDismissed(storage,out.dutyPromptDismissalKey('user-1','2026-11-18',options(null))),false)
assert.equal(out.wasDutyPromptDismissed({getItem(){throw Error('unavailable')}},morning),false)
assert.doesNotThrow(()=>out.dismissDutyPrompt({setItem(){throw Error('unavailable')}},morning))
console.log('Dashboard morning, night and straight-duty options: PASS')
